export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Lit pixels of `text` (uppercased) as [x, y] in glyph units, 1 unit of spacing per letter. */
export function textPixels(text: string): { pixels: [number, number][]; width: number } {
  const pixels: [number, number][] = [];
  let x = 0;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch];
    if (!glyph) throw new Error(`pixel font has no glyph for "${ch}"`);
    glyph.forEach((row, y) => {
      for (let i = 0; i < GLYPH_W; i++) if (row[i] === "#") pixels.push([x + i, y]);
    });
    x += GLYPH_W + 1;
  }
  return { pixels, width: Math.max(0, x - 1) };
}
